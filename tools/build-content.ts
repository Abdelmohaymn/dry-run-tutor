#!/usr/bin/env -S node
// tools/build-content.ts — data-model.md §B5. Splits authored problems into
// the public manifest the app may prefetch and the private store only the
// Worker bundle ever holds. Fails the build rather than ship broken or
// leaking content (FR-028, FR-029, SC-013, SC-014).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { validateAll, type ValidationResult } from "./validate-content";
import type { Problem } from "./problem-types";

// data-model.md §B5. Two independent checks — key names AND verbatim
// content — because a rename would defeat the name check alone.
const PRIVATE_KEYS = [
  "reference_approaches",
  "key_insights",
  "common_wrong_turns",
  "edge_cases",
  "followups",
  "editorial",
  "hints",
  "never_say",
  "counter_question",
  "failing_case",
  "why_it_fails",
  "model_answer",
  "grading_note",
  "sketch",
];

export interface PrivateLeakResult {
  ok: boolean;
  failures: string[];
}

export function assertNoPrivateLeak(manifest: unknown, problems: Problem[]): PrivateLeakResult {
  const failures: string[] = [];
  const blob = JSON.stringify(manifest);

  for (const key of PRIVATE_KEYS) {
    if (blob.includes(`"${key}"`)) {
      failures.push(`private key name '${key}' is reachable from the public manifest`);
    }
  }
  for (const problem of problems) {
    const editorialPrefix = problem.private.editorial.slice(0, 80);
    if (editorialPrefix && blob.includes(editorialPrefix)) {
      failures.push(`editorial content for '${problem.public.id}' is reachable from the public manifest`);
    }
    for (const approach of problem.private.reference_approaches) {
      for (const sketchLine of approach.sketch) {
        if (blob.includes(sketchLine)) {
          failures.push(
            `sketch content for approach '${approach.key}' on '${problem.public.id}' is reachable from the public manifest`,
          );
        }
      }
    }
  }

  return { ok: failures.length === 0, failures };
}

function loadProblemFiles(dir: string): unknown[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => JSON.parse(readFileSync(path.join(dir, f), "utf-8")));
}

export interface BuildResult {
  publicManifest: { schema_version: 2; generated: string; problems: unknown[] };
  privateStoreSource: string;
}

export function build(rawProblems: unknown[]): BuildResult {
  const results: ValidationResult[] = validateAll(rawProblems);
  const failing = results.filter((r) => r.failures.length > 0);
  if (failing.length > 0) {
    const lines = failing.flatMap((r) => [
      `  ${r.problemId}:`,
      ...r.failures.map((f) => `     rule${f.rule}  ${f.message}`),
    ]);
    throw new Error(`content build failed validation:\n${lines.join("\n")}`);
  }

  const problems = results.map((r) => r.problem as Problem);

  const publicEntries = problems.map((p) => ({
    ...p.public,
    // T027a: build-injected, never authored (data-model.md §A1, FR-030).
    hint_count: 3 * p.private.key_insights.length,
  }));

  const publicManifest = {
    schema_version: 2 as const,
    generated: new Date().toISOString(),
    problems: publicEntries,
  };

  const leakCheck = assertNoPrivateLeak(publicManifest, problems);
  if (!leakCheck.ok) {
    throw new Error(`content build failed the private-leak assertion:\n${leakCheck.failures.map((f) => `  ${f}`).join("\n")}`);
  }

  const privateStore: Record<string, Problem["private"]> = {};
  for (const p of problems) {
    privateStore[p.public.id] = p.private;
  }

  const privateStoreSource = `// GENERATED by tools/build-content.ts. Do not edit by hand.\nexport const PRIVATE = ${JSON.stringify(privateStore, null, 2)} as const;\n`;

  return { publicManifest, privateStoreSource };
}

function main(): number {
  const contentDir = path.resolve("../content/problems");
  const generatedDir = path.resolve("src/generated");

  const rawProblems = loadProblemFiles(contentDir);
  let result: BuildResult;
  try {
    result = build(rawProblems);
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    return 1;
  }

  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(
    path.join(generatedDir, "public-manifest.json"),
    JSON.stringify(result.publicManifest, null, 2) + "\n",
  );
  writeFileSync(path.join(generatedDir, "private-store.ts"), result.privateStoreSource);

  console.log(`built ${result.publicManifest.problems.length} problem(s) -> src/generated/`);
  return 0;
}

const isMain = Boolean(process.argv[1]) && path.resolve(process.argv[1]!) === fileURLToPath(import.meta.url);
if (isMain) {
  process.exit(main());
}
